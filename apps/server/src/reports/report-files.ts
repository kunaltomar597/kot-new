import { createRequire } from 'node:module';
import { dirname } from 'node:path';
import { EXPORT_ROW_LIMITS, type ExportFormat } from '@rp/contracts';
import { type ColumnKind, displayValue, type ReportCell, type ReportDocument } from '@rp/domain';
import ExcelJS from 'exceljs';
import { AppError } from '../errors/app-error.js';
import pdfmake, { type Content, type DocumentDefinition, type TableCell } from 'pdfmake';

/**
 * Excel and PDF files of a report document (P4-06, RPT-017). CSV comes from `@rp/domain`
 * `documentToCsv`; all three start with the same stamp and show the same tables.
 */

// ---------------------------------------------------------------- limits

/** The error for a file too long for its format, or undefined when it fits (CSV always fits). */
export function exportTooLarge(format: ExportFormat, rows: number): AppError | undefined {
  if (format === 'CSV' || rows <= EXPORT_ROW_LIMITS[format]) return undefined;
  const limit = EXPORT_ROW_LIMITS[format];
  return new AppError(
    422,
    'EXPORT_TOO_LARGE',
    `This report has ${String(rows)} rows; ${format === 'PDF' ? 'a PDF' : 'an Excel file'} takes at most ${String(limit)}. Export it as CSV, or choose a shorter period.`,
    { rows, limit },
  );
}

// ---------------------------------------------------------------- Excel

/** A sheet name Excel accepts: at most 31 characters, none of `[]:*?/\`, unique in the book. */
function sheetName(wanted: string, used: Set<string>): string {
  const base =
    wanted
      .replace(/[[\]:*?/\\]/g, ' ')
      .slice(0, 28)
      .trim() || 'Report';
  let candidate = base;
  for (let number = 2; used.has(candidate.toLowerCase()); number += 1) {
    candidate = `${base} ${String(number)}`;
  }
  used.add(candidate.toLowerCase());
  return candidate;
}

/**
 * A cell as Excel stores it: money in rupees and percentages as numbers (so columns sum and
 * format), everything else as written. Text is always text: Excel never runs it as a formula.
 */
function excelValue(kind: ColumnKind, cell: ReportCell): string | number | null {
  if (cell === null || typeof cell === 'string') return cell;
  return kind === 'money' || kind === 'percent' ? cell / 100 : cell;
}

const EXCEL_FORMATS: Partial<Record<ColumnKind, string>> = {
  money: '#,##0.00',
  percent: '0.00',
  number: '#,##0',
};

export async function documentToXlsx(document: ReportDocument): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'Restaurant Operations Platform';
  const used = new Set<string>();
  const tables = document.tables.length === 0 ? [{ columns: [], rows: [] }] : document.tables;
  for (const table of tables) {
    const sheet = workbook.addWorksheet(
      sheetName(
        'heading' in table && table.heading !== undefined ? table.heading : document.stamp.title,
        used,
      ),
    );
    const { stamp } = document;
    sheet.addRow([stamp.title]).font = { bold: true, size: 14 };
    sheet.addRow(['Restaurant', stamp.restaurant]);
    for (const [label, value] of stamp.filters) sheet.addRow([label, value]);
    sheet.addRow(['Generated by', stamp.generatedBy]);
    sheet.addRow(['Generated at', stamp.generatedAt]);
    sheet.addRow([]);
    const header = sheet.addRow(table.columns.map((column) => column.label));
    header.font = { bold: true };
    sheet.views = [{ state: 'frozen', ySplit: header.number }];
    table.rows.forEach((row, rowIndex) => {
      const added = sheet.addRow(
        row.map((cell, index) => excelValue(table.columns[index]?.kind ?? 'text', cell)),
      );
      table.columns.forEach((column, index) => {
        const format = EXCEL_FORMATS[column.kind];
        if (format !== undefined) added.getCell(index + 1).numFmt = format;
      });
      if ('totalRow' in table && table.totalRow === true && rowIndex === table.rows.length - 1) {
        added.font = { bold: true };
      }
    });
    table.columns.forEach((column, index) => {
      const longest = Math.max(
        column.label.length,
        ...table.rows
          .slice(0, 500)
          .map((row) => displayValue(column.kind, row[index] ?? null).length),
      );
      sheet.getColumn(index + 1).width = Math.min(40, Math.max(10, longest + 2));
    });
  }
  return Buffer.from(await workbook.xlsx.writeBuffer());
}

// ---------------------------------------------------------------- PDF

const require = createRequire(import.meta.url);
/** Roboto as shipped with pdfmake: it has the ₹ sign. */
const FONTS = require('pdfmake/fonts/Roboto') as {
  Roboto: { normal: string; bold: string; italics: string; bolditalics: string };
};
const FONT_DIR = dirname(FONTS.Roboto.normal);
pdfmake.setFonts(FONTS);
// Reports never load anything from the network or the disk beyond the fonts.
pdfmake.setUrlAccessPolicy(() => false);
pdfmake.setLocalAccessPolicy((path) => path.startsWith(FONT_DIR));

const NUMERIC: ReadonlySet<ColumnKind> = new Set(['money', 'number', 'percent']);

export async function documentToPdf(document: ReportDocument): Promise<Buffer> {
  const { stamp } = document;
  const widest = Math.max(0, ...document.tables.map((table) => table.columns.length));
  const content: Content[] = [
    { text: stamp.title, style: 'title' },
    {
      text: [
        stamp.restaurant,
        ...stamp.filters.map(([label, value]) => `${label}: ${value}`),
        `Generated by ${stamp.generatedBy}, ${stamp.generatedAt}`,
      ].join('   ·   '),
      style: 'stamp',
    },
  ];
  for (const table of document.tables) {
    if (table.heading !== undefined) content.push({ text: table.heading, style: 'heading' });
    const header: TableCell[] = table.columns.map((column) => ({
      text: column.label,
      style: 'header',
      alignment: NUMERIC.has(column.kind) ? 'right' : 'left',
    }));
    const body: TableCell[][] = [
      header,
      ...table.rows.map((row, rowIndex) =>
        table.columns.map((column, index) => ({
          text: displayValue(column.kind, row[index] ?? null),
          alignment: NUMERIC.has(column.kind) ? ('right' as const) : ('left' as const),
          bold: table.totalRow === true && rowIndex === table.rows.length - 1,
        })),
      ),
    ];
    content.push(
      table.rows.length === 0
        ? { text: 'Nothing in this period.', style: 'empty' }
        : {
            table: {
              headerRows: 1,
              widths: table.columns.map((column) => (column.kind === 'text' ? '*' : 'auto')),
              body,
            },
            layout: 'lightHorizontalLines',
          },
    );
  }
  const definition: DocumentDefinition = {
    pageSize: 'A4',
    pageOrientation: widest > 6 ? 'landscape' : 'portrait',
    pageMargins: [28, 28, 28, 36],
    info: {
      title: stamp.title,
      author: stamp.restaurant,
      creator: 'Restaurant Operations Platform',
    },
    content,
    footer: (page, pages) => ({
      text: `${stamp.title} · ${stamp.restaurant} · page ${String(page)} of ${String(pages)}`,
      style: 'footer',
    }),
    defaultStyle: { font: 'Roboto', fontSize: 8 },
    styles: {
      title: { fontSize: 14, bold: true, margin: [0, 0, 0, 4] },
      stamp: { fontSize: 8, color: '#475569', margin: [0, 0, 0, 10] },
      heading: { fontSize: 10, bold: true, margin: [0, 10, 0, 4] },
      header: { bold: true },
      empty: { italics: true, color: '#475569' },
      footer: { fontSize: 7, color: '#475569', alignment: 'center', margin: [0, 12, 0, 0] },
    },
  };
  return pdfmake.createPdf(definition).getBuffer();
}
