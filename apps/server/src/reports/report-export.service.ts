import { Injectable } from '@nestjs/common';
import {
  EXPORT_CONTENT_TYPES,
  type ReportExportRequest,
  type ReportExportResponse,
} from '@rp/contracts';
import { documentToCsv, type ReportDocument, reportRowCount } from '@rp/domain';
import { AuditService } from '../audit/audit.service.js';
import type { Principal } from '../auth/principal.js';
import { PrismaService } from '../database/prisma.service.js';
import { formatLocal } from '../printing/escpos.js';
import { REPORT_TITLES, ReportDocumentsService } from './report-documents.service.js';
import { documentToPdf, documentToXlsx, exportTooLarge } from './report-files.js';

const EXTENSIONS = { CSV: 'csv', XLSX: 'xlsx', PDF: 'pdf' } as const;

/**
 * Report exports (P1-13b, P4-06, RPT-017): every report as CSV, Excel or PDF, from the same
 * figures as the screen. The file starts with the stamp the BRD asks for (restaurant, report,
 * filters, generated by and at), and every export is audited as REPORT_EXPORTED with its format.
 */
@Injectable()
export class ReportExportService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly documents: ReportDocumentsService,
    private readonly audit: AuditService,
  ) {}

  /** `ownShiftsOf` is set for a cashier (OWN): only their own shift report may be exported. */
  async export(
    principal: Principal,
    request: ReportExportRequest,
    ownShiftsOf: string | null,
  ): Promise<ReportExportResponse> {
    const restaurantId = principal.restaurantId;
    const [restaurant, staff] = await Promise.all([
      this.prisma.restaurant.findUniqueOrThrow({
        where: { id: restaurantId },
        select: { displayName: true, timeZone: true },
      }),
      this.prisma.staff.findUniqueOrThrow({
        where: { id: principal.staffId },
        select: { displayName: true },
      }),
    ]);
    const range = { from: request.from, to: request.to };
    const tables = await this.documents.tables(
      restaurantId,
      request.report,
      range,
      ownShiftsOf,
      restaurant.timeZone,
    );
    const now = new Date();
    const filters: [string, string][] = [
      ['From', request.from],
      ['To', request.to],
    ];
    if (ownShiftsOf !== null) filters.push(['Shifts of', staff.displayName]);
    const document: ReportDocument = {
      stamp: {
        title: REPORT_TITLES[request.report],
        restaurant: restaurant.displayName,
        filters,
        generatedBy: staff.displayName,
        generatedAt: `${formatLocal(now, restaurant.timeZone)} (${restaurant.timeZone})`,
      },
      tables,
    };
    const rows = reportRowCount(document);
    const format = request.format;
    const tooLarge = exportTooLarge(format, rows);
    if (tooLarge !== undefined) throw tooLarge;
    const filename = `${request.report.toLowerCase().replace(/_/g, '-')}_${request.from}_${request.to}.${EXTENSIONS[format]}`;
    const content =
      format === 'CSV'
        ? documentToCsv(document)
        : (format === 'XLSX'
            ? await documentToXlsx(document)
            : await documentToPdf(document)
          ).toString('base64');
    await this.prisma.transaction(async (tx) => {
      await this.audit.record(tx, {
        action: 'REPORT_EXPORTED',
        entityType: 'report',
        entityId: null,
        actorId: principal.staffId,
        deviceId: principal.deviceId,
        restaurantId,
        before: null,
        after: {
          report: request.report,
          format,
          from: request.from,
          to: request.to,
          ownShiftsOnly: ownShiftsOf !== null,
          filename,
          rows,
        },
        reason: null,
      });
    });
    return {
      filename,
      contentType: EXPORT_CONTENT_TYPES[format],
      encoding: format === 'CSV' ? 'utf-8' : 'base64',
      content,
      generatedAt: now.toISOString(),
    };
  }
}
